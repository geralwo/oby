/* blob_gen — bake a file's bytes into a C accessor.
 *
 *   blob_gen <out.c> <symbol> <file>
 *
 * Emits `const unsigned char *<symbol>(size_t *len)`. `compile.sh` uses it to
 * put the runner inside the toolchain, so `oby` can write standalone
 * executables without a second file on hand. (Source files go through
 * `tools/embed_gen.c` instead.)
 */
#include <stdio.h>
#include <stdlib.h>

static void *xmalloc(size_t size) {
    void *p = malloc(size);
    if (!p) {
        fprintf(stderr, "blob_gen: out of memory\n");
        exit(1);
    }
    return p;
}

int main(int argc, char **argv) {
    if (argc != 4) {
        fprintf(stderr, "usage: %s <out.c> <symbol> <file>\n", argv[0]);
        return 1;
    }
    const char *out_path = argv[1];
    const char *symbol = argv[2];
    const char *in_path = argv[3];

    FILE *in = fopen(in_path, "rb");
    if (!in) {
        fprintf(stderr, "blob_gen: cannot read '%s'\n", in_path);
        return 1;
    }
    if (fseek(in, 0, SEEK_END) != 0) {
        fclose(in);
        fprintf(stderr, "blob_gen: cannot read '%s'\n", in_path);
        return 1;
    }
    long size = ftell(in);
    if (size < 0) {
        fclose(in);
        fprintf(stderr, "blob_gen: cannot read '%s'\n", in_path);
        return 1;
    }
    rewind(in);
    unsigned char *data = (unsigned char *)xmalloc((size_t)size + 1);
    size_t got = fread(data, 1, (size_t)size, in);
    fclose(in);
    if (got != (size_t)size) {
        fprintf(stderr, "blob_gen: cannot read '%s'\n", in_path);
        return 1;
    }

    FILE *out = fopen(out_path, "wb");
    if (!out) {
        fprintf(stderr, "blob_gen: cannot write '%s'\n", out_path);
        return 1;
    }

    fprintf(out, "/* Generated by tools/blob_gen.c from %s — do not edit. */\n",
            in_path);
    fputs("#include <stddef.h>\n#include \"core/bundle.h\"\n\n", out);
    fputs("static const unsigned char blob[] = {\n", out);
    if (got == 0) fputs("    0\n", out);
    for (size_t i = 0; i < got; i++) {
        if (i % 12 == 0) fputs("    ", out);
        fprintf(out, "0x%02x,", data[i]);
        if (i % 12 == 11 || i + 1 == got) fputc('\n', out);
        else fputc(' ', out);
    }
    fputs("};\n\n", out);
    fprintf(out,
            "const unsigned char *%s(size_t *len) {\n"
            "    *len = %zu;\n"
            "    return blob;\n"
            "}\n",
            symbol, got);

    if (fclose(out) != 0) {
        fprintf(stderr, "blob_gen: cannot write '%s'\n", out_path);
        return 1;
    }
    free(data);
    return 0;
}
